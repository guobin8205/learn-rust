// ===== 8.1 Vec<T> 动态数组 =====
// 用 cargo run --bin vec_t 运行

fn main() {
    // ========================================================
    // 一、创建 Vec
    // ========================================================

    // 方式 1：Vec::new()，需要标注类型（因为还没有数据推断）
    let v1: Vec<i32> = Vec::new();

    // 方式 2：vec! 宏，直接带初始值（最常用）
    let v2 = vec![1, 2, 3, 4, 5];
    println!("v2 = {:?}", v2);

    let v3 = vec![0; 5];    // 5 个 0，等价于 vec![0, 0, 0, 0, 0]
    println!("v3 = {:?}", v3);

    // ========================================================
    // 二、添加元素：push
    // ========================================================
    let mut v = Vec::new();   // 注意必须 mut 才能 push
    v.push(1);
    v.push(2);
    v.push(3);
    println!("push 后 v = {:?}", v);

    // ========================================================
    // 三、读取元素（两种方式，安全性不同 ⭐）
    // ========================================================

    let v = vec![10, 20, 30, 40, 50];

    // 方式 1：索引 [index] —— 越界会 panic 💥
    let third = &v[2];
    println!("v[2] = {third}");

    // 方式 2：.get(index) —— 返回 Option<&T>，越界返回 None（安全 ✅）
    match v.get(2) {
        Some(val) => println!("v.get(2) = {val}"),
        None => println!("没有第三元素"),
    }

    // 对比越界行为：
    // let crash = &v[100];        // ❌ panic: index out of bounds
    let safe = v.get(100);          // ✅ 返回 None
    println!("v.get(100) = {:?}", safe);

    // 💡 经验：用户输入的索引用 .get()，确定安全的索引用 []

    // ========================================================
    // 四、遍历 Vec
    // ========================================================
    let v = vec![100, 200, 300];

    // ① 不可变遍历（只读）
    for val in &v {            // &v 借用，不拿走所有权
        println!("值: {val}");
    }

    // ② 可变遍历（修改元素）
    let mut v = vec![1, 2, 3];
    for val in &mut v {        // *val 解引用后修改
        *val *= 10;
    }
    println!("可变遍历后: {:?}", v);   // [10, 20, 30]

    // ③ 消耗遍历（拿走所有权）
    let v = vec![String::from("a"), String::from("b")];
    for s in v {               // 直接遍历 v（不是 &v），消耗所有权
        println!("消耗: {s}");
    }
    // println!("{:?}", v);    // ❌ v 已被消耗

    // ========================================================
    // 五、所有权与借用规则（结合第 4 章）
    // ========================================================
    let mut v = vec![1, 2, 3, 4, 5];
    let first = &v[0];          // 不可变借用
    println!("第一个元素: {first}");   // ← first 在这里最后一次使用

    v.push(6);                  // ✅ 可变借用（因为 first 已不再使用，NLL）
    println!("push 后: {:?}", v);

    // ⚠️ 如果这样写就会报错：
    // let first = &v[0];
    // v.push(6);              // ❌ 此时 first 还要被使用，不可变借用和可变借用冲突
    // println!("{first}");

    // 💡 为什么 push 会影响借用？因为 Vec 可能扩容（搬移内存），
    //    旧的引用会变成悬垂指针！借用检查器防止这种情况

    // ========================================================
    // 六、常用方法速查
    // ========================================================
    let mut v = vec![3, 1, 4, 1, 5, 9, 2, 6];

    println!("长度: {}", v.len());
    println!("是否空: {}", v.is_empty());

    let last = v.pop();         // 弹出最后一个
    println!("pop: {:?}", last);
    println!("pop 后: {:?}", v);

    v.sort();                   // 排序（原地）
    println!("排序后: {:?}", v);

    v.reverse();                // 反转
    println!("反转后: {:?}", v);

    let sum: i32 = v.iter().sum();   // 求和（迭代器，第 13 章详讲）
    println!("求和: {sum}");

    // ========================================================
    // 七、存储不同类型的数据：用 enum（结合第 6 章）⭐
    // ========================================================
    // Vec 要求所有元素类型相同。要存不同类型，用 enum：

    let row = vec![
        SpreadsheetCell::Int(3),
        SpreadsheetCell::Text(String::from("blue")),
        SpreadsheetCell::Float(10.12),
    ];
    println!("表格行: {:?}", row);

    // ========================================================
    // ⭐ Vec 速查表
    // ========================================================
    // | 操作           | 方法                    |
    // |---------------|------------------------|
    // | 创建空          | Vec::new() 或 vec![]    |
    // | 创建带初值       | vec![1,2,3]            |
    // | 添加元素        | v.push(val)            |
    // | 删除末尾元素     | v.pop() → Option<T>    |
    // | 读取（panic）   | &v[i]                  |
    // | 读取（安全）    | v.get(i) → Option<&T>  |
    // | 长度           | v.len()                |
    // | 是否为空        | v.is_empty()           |
    // | 遍历只读        | for x in &v            |
    // | 遍历可变        | for x in &mut v        |
    // | 包含某值        | v.contains(&val)       |
}

#[derive(Debug)]
enum SpreadsheetCell {
    Int(i32),
    Float(f64),
    Text(String),
}
