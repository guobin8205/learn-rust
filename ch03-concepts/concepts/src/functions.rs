// ===== 3.3 函数 (Functions) =====
// 用 cargo run --bin functions 运行本文件

fn main() {
    another_function(5, 'h');        // 调用带参数的函数

    let r = add(3, 4);               // 函数有返回值
    println!("3 + 4 = {r}");

    let m = max(10, 20);             // 条件返回
    println!("max(10, 20) = {m}");

    let five = get_five();           // 无 return，用表达式返回
    println!("five = {five}");

    // ⚠️ 语句 vs 表达式（Rust 中极其重要的区分！）
    let x = 5;                       // 语句（以分号结尾）
    let y = {                        // 块也是表达式！块的值是最后一个表达式的值
        let z = 3;
        z + 1                        // ← 注意没有分号！这是"表达式"，作为整个块的值
    };                               // y = 4
    println!("x={x}, y={y}");

    // 控制流也是表达式，可以用于赋值
    let condition = true;
    let n = if condition { 5 } else { 6 };  // if 是表达式
    println!("n = {n}");
}

// ---------- 函数定义 ----------
// fn 函数名(参数名: 类型, ...) -> 返回类型
fn another_function(value: i32, unit_label: char) {
    println!("测量值：{value}{unit_label}");
}

// ---------- 带返回值的函数 ----------
// 返回类型用 -> 标注
// 注意：函数体最后一个"表达式"（无分号）就是返回值
fn add(a: i32, b: i32) -> i32 {
    a + b     // ← 没有分号！这是表达式，它的值被返回
    // 等价于: return a + b;（return 关键字通常只在提前返回时用）
}

// ---------- 提前返回用 return ----------
fn max(a: i32, b: i32) -> i32 {
    if a > b {
        return a;   // 提前返回
    }
    b               // 默认返回最后一个表达式
}

// ---------- 简单情况可以非常简洁 ----------
fn get_five() -> i32 {
    5               // 直接返回字面量
}

// ========================================================
// 🔑 核心概念：语句 (Statement) vs 表达式 (Expression)
// ========================================================
//
// 语句 (Statement)：执行操作但不返回值，以分号结尾
//   let x = 5;          // 语句
//   fn foo() {}         // 语句
//
// 表达式 (Expression)：求值并返回一个值，不能以分号结尾
//   5                   // 表达式，值为 5
//   x + 1               // 表达式
//   if cond { 1 } else { 2 }   // 表达式
//   { let y = 1; y + 1 }       // 块也是表达式
//
// ⚠️ 关键陷阱：加了分号就变成语句，返回 ()（单元类型）
//   { let y = 1; y + 1; }      // 加了分号 → 块的值变成 ()，不是 2！
//
// 这个区分贯穿整个 Rust，是理解很多语法的关键：
//   - 函数返回值（最后一个表达式）
//   - match/if/loop 作为表达式
//   - 块作用域 {}
