// ===== 3.2 数据类型 (Data Types) =====
// 用 cargo run --bin data_types 运行本文件

fn main() {
    // ========================================================
    // 一、标量类型 (Scalar) —— 单个值
    // ========================================================

    // ---------- ① 整数类型 ----------
    // 有符号: i8 i16 i32 i64 i128 isize    范围：-(2^n-1) ~ 2^n-1 - 1
    // 无符号: u8 u16 u32 u64 u128 usize    范围：0 ~ 2^n - 1
    let a: i32 = -5;          // 32 位有符号（i32 是默认整数类型）
    let b: u64 = 100;         // 64 位无符号
    let c: isize = -10;       // 等于机器字长（64 位机器上 = i64）
    println!("整数: a={a}, b={b}, c={c}");

    // 整数字面量的多种写法
    let decimal     = 98_222;   // 十进制（下划线分隔）
    let hex         = 0xff;     // 十六进制
    let octal       = 0o77;     // 八进制
    let binary      = 0b1111_0000; // 二进制
    let byte        = b'A';     // 字节（u8），值是 A 的 ASCII 码 65
    println!("字面量: {decimal}, {hex}, {octal}, {binary}, {byte}");

    // ⚠️ 整数溢出：debug 模式会 panic，release 模式会环绕（wrap around）
    // 例如 u8 最大 255，加 1 在 debug 模式 panic，release 模式变 0

    // ---------- ② 浮点类型 ----------
    let x = 2.0;       // f64（默认浮点类型，64 位双精度）
    let y: f32 = 3.0;  // f32（32 位单精度）
    println!("浮点: x={x}, y={y}");

    // ---------- ③ 布尔类型 ----------
    let t = true;           // 推断为 bool
    let f: bool = false;    // 显式标注
    println!("布尔: t={t}, f={f}");

    // ---------- ④ 字符类型 ----------
    let c = 'z';            // char 类型，用单引号
    let emoji = '😀';       // char 是 4 字节 Unicode 标量值
    println!("字符: {c}, {emoji}");

    // ⚠️ char（单引号，4字节 Unicode）≠ String/&str（双引号，UTF-8 字节序列）

    // ========================================================
    // 二、复合类型 (Compound) —— 多个值组合
    // ========================================================

    // ---------- ⑤ 元组 Tuple ----------
    let tup: (i32, f64, u8) = (500, 6.4, 1);  // 固定长度、可不同类型
    // 解构（destructuring）：把元组拆开
    let (x, y, z) = tup;
    println!("解构: x={x}, y={y}, z={z}");
    // 用 .索引 访问（从 0 开始）
    println!("点访问: tup.0={}, tup.1={}, tup.2={}", tup.0, tup.1, tup.2);

    // 单元类型 ()：空元组，表示"没有有意义的值"
    let _unit: () = ();

    // ---------- ⑥ 数组 Array ----------
    // 固定长度、相同类型、分配在栈上
    let arr = [1, 2, 3, 4, 5];           // [i32; 5]
    let months = ["Jan", "Feb", "Mar"];  // [&str; 3]
    println!("数组: {:?}, {:?}", arr, months);

    // 创建初始化数组：[值; 长度]
    let zeros = [0; 5];  // 五个 0，等价于 [0, 0, 0, 0, 0]
    println!("zeros = {:?}", zeros);

    // 访问数组元素
    let first = arr[0];   // 1
    let last = arr[4];    // 5
    println!("first={first}, last={last}");

    // ⚠️ 数组越界：运行时 panic（debug 和 release 都是）
    // let oob = arr[10];  // ❌ panic: index out of bounds

    // ========================================================
    // 三、数组 vs 元组 vs Vec 对比（预告）
    // ========================================================
    // | 类型   | 长度   | 元素类型 | 内存   | 详讲  |
    // |--------|--------|---------|--------|-------|
    // | Tuple  | 固定   | 可不同  | 栈     | 本章  |
    // | Array  | 固定   | 必须相同| 栈     | 本章  |
    // | Vec    | 可变   | 必须相同| 堆     | 第8章 |
}
