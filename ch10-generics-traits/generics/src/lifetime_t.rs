// ===== 10.3 生命周期 (Lifetimes) =====
// 用 cargo run --bin lifetime_t 运行

// ========================================================
// 一、生命周期解决什么问题？
// ========================================================
// 问题：引用必须始终有效（不能悬垂）。编译器需要知道每个引用「活多久」
// 大部分时候编译器能自动推断，但有些情况需要我们手动标注

// =====================================================  ===
// 二、悬垂引用（编译器阻止的危险代码）
// ========================================================
// fn dangle() -> &String {     // ❌ 编译错误
//     let s = String::from("hi");
//     &s   // s 在函数结束时被 drop，返回的引用会悬垂！
// }

// ========================================================
// 三、生命周期标注语法：'a
// ========================================================
// 'a 是一个「生命周期参数」，表示「这两个引用至少活一样久」
// 注意：'a 不改变实际生命周期，只是告诉编译器它们的关系

// ---------- 最长字符串函数 ----------
// 不加生命周期标注会编译错误（编译器不知道返回的引用和谁的生命周期绑定）
fn longest<'a>(x: &'a str, y: &'a str) -> &'a str {
    if x.len() > y.len() {
        x
    } else {
        y
    }
}
// 解读：x、y、返回值三个引用的生命周期至少是 'a（至少活一样久）
// 意味着「返回值的生命周期 = x 和 y 中较短的那个」

// ========================================================
// 四、生命周期标注的理解（关键）
// ========================================================
// 'a 是一个「约束」，不是「修改」
// 类比泛型 <T>：T 是「任意类型」
// 生命周期 'a：表示「某个生命周期，多个引用都至少活这么久」
//
// 当 x 和 y 的实际生命周期不同时：
//   x 活得久，y 活得短 → 'a = 较短的那个（y 的）
//   返回值只能在 y 还活着时使用

fn main() {
    // ---------- 基本用法 ----------
    let s1 = String::from("long string");
    let s2 = String::from("short");
    let result = longest(s1.as_str(), s2.as_str());
    println!("更长的: {}", result);

    // ---------- 生命周期限制的实际效果 ----------
    let s1 = String::from("hello");
    let result;
    {
        let s2 = String::from("world!");
        result = longest(s1.as_str(), s2.as_str());
        println!("内部使用: {}", result);   // ✅ s2 还活着
    }
    // println!("{}", result);   // ❌ 编译错误！s2 已 drop，result 可能指向 s2

    // ========================================================
    // 五、结构体中的生命周期
    // ========================================================
    // 结构体字段是引用时，必须标注生命周期
    let novel = String::from("Call me Ishmael. Some years ago...");
    let first = novel.split('.').next().unwrap();
    let excerpt = Excerpt { part: first };
    println!("摘录: {}", excerpt.part);
    // excerpt 的生命周期不能超过 novel（novel 没了，excerpt.part 就悬垂了）

    // ========================================================
    // 六、静态生命周期 'static（重要概念）
    // ========================================================
    // 'static 表示「整个程序运行期间都有效」
    let s: &'static str = "所有字符串字面量都是 'static";
    println!("{}", s);
    // 字符串字面量存在二进制文件里，永远有效，所以是 &'static str

    // ========================================================
    // 七、生命周期消除规则（编译器自动做的）
    // ========================================================
    // 很多时候不用写生命周期，因为编译器按规则自动推断：
    //
    // 规则 1：每个引用参数都获得独立的生命周期
    // 规则 2：只有一个输入生命周期时，它被赋给所有输出生命周期
    // 规则 3：方法（有 &self/&mut self）时，self 的生命周期赋给所有输出
    //
    // 例：fn foo(x: &str) -> &str 自动变成 fn foo<'a>(x: &'a str) -> &'a str
}

// ========================================================
// 结构体中的生命周期标注
// ========================================================
// 结构体持有引用时，必须标注生命周期
// 表示「这个结构体不能比它引用的数据活得更久」
struct Excerpt<'a> {
    part: &'a str,    // part 引用的数据必须比 excerpt 活得久
}

// ========================================================
// 带生命周期的 impl 块
// ========================================================
impl<'a> Excerpt<'a> {
    // 规则 3：self 的生命周期赋给返回值
    fn announce(&self, msg: &str) -> &str {
        println!("请注意: {}", msg);
        self.part
    }
}

// ========================================================
// 八、泛型 + Trait + 生命周期 三合一（终极形态）
// ========================================================
use std::fmt::Display;

fn longest_with_announcement<'a, T>(
    x: &'a str,
    y: &'a str,
    ann: T,
) -> &'a str
where
    T: Display,
{
    println!("公告: {}", ann);
    if x.len() > y.len() {
        x
    } else {
        y
    }
}

// ========================================================
// ⭐ 生命周期速查
// ========================================================
// | 场景                  | 要标注吗？ |
// |----------------------|----------|
// | 函数参数和返回都是引用 | 通常要     |
// | 结构体字段是引用       | 必须要     |
// | 只有参数引用无返回引用  | 通常不用   |
// | 方法里用 &self        | 通常不用   |
//
// 💡 经验：先不写生命周期标注，让编译器告诉你哪里需要！
//    编译器的错误提示非常好，会告诉你该怎么标。
