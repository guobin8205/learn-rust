// ===== 4.3 切片 (Slices) =====
// 用 cargo run --bin slices 运行

fn main() {
    // ========================================================
    // 切片：引用集合中「连续的一部分」，不拥有所有权
    // 解决问题：安全地引用某段数据的一部分
    // ========================================================

    // ---------- ① 字符串切片 &str ----------
    let s = String::from("hello world");

    let hello = &s[0..5];      // "hello"，[0,5) 半开区间
    let world = &s[6..11];     // "world"
    println!("切片: {hello}, {world}");

    // 简写：从头开始 ..n 等价于 0..n
    let hello2 = &s[..5];      // "hello"
    // 简写：到末尾 n.. 等价于 n..len
    let world2 = &s[6..];      // "world"
    // 简写：整个 &s[..]
    let whole = &s[..];        // "hello world"
    println!("{hello2}, {world2}, {whole}");

    // 切片在内存中的样子：
    //   栈：s → [ptr,len,cap] ──→ 堆: [h][e][l][l][o][ ][w][o][r][l][d]
    //                     ↑                                  ↑
    //   切片 &s[0..5]: [ptr,len=5]──┘                                  │
    //   切片 &s[6..11]: [ptr,len=5]───────────────────────────────────┘
    //   切片只存「起始指针 + 长度」，不拥有堆数据

    // ---------- ② 字符串字面量就是切片 ----------
    let literal: &str = "hello world";   // 字面量的类型是 &str
    // 字面量 "hello world" 直接存在二进制文件里，&str 是指向它的切片
    println!("字面量: {literal}");

    // ---------- ③ String vs &str ----------
    // | 类型   | 所有权 | 可变性 | 内存           |
    // |--------|--------|--------|----------------|
    // | String | 有     | 可变   | 堆，可增长      |
    // | &str   | 无     | 只读   | 指向某处字符串   |

    // ---------- ④ 用切片重构函数（the book 经典例子）----------
    let essay = String::from("hello world, hello rust");
    let word = first_word(&essay);   // 返回第一个单词的切片
    println!("第一个单词: {word}");    // "hello"
    // 如果 essay 后来被清空，word 就会变成「悬垂引用」——但编译器会阻止！
    // essay.clear();   // ❌ 编译错误（违反借用规则）
    // println!("{word}");

    // ---------- ⑤ 函数参数用 &str 更通用 ----------
    // 最佳实践：函数参数优先用 &str 而非 &String
    // 因为 &String 能自动转成 &str（解引用强制转换 deref coercion）
    let s1 = String::from("hello");
    let s2 = "world";   // 字面量就是 &str
    print_str(&s1);     // ✅ &String 自动转 &str
    print_str(s2);      // ✅ 本来就是 &str

    // ========================================================
    // 六、其他类型的切片
    // ========================================================
    let arr = [1, 2, 3, 4, 5];
    let slice: &[i32] = &arr[1..4];   // 数组切片 [2, 3, 4]
    println!("数组切片: {slice:?}");

    // ========================================================
    // ⭐ 所有权 / 借用 / 切片 三者关系总结
    // ========================================================
    // | 概念   | 语法     | 所有权 | 用途              |
    // |--------|----------|--------|-------------------|
    // | 移动   | s        | 有     | 拥有数据          |
    // | 借用   | &s / &mut s | 无  | 读/写但不拥有     |
    // | 切片   | &s[..] / &[T] | 无 | 引用数据的一部分 |
}

fn first_word(s: &str) -> &str {
    let bytes = s.as_bytes();

    for (i, &item) in bytes.iter().enumerate() {
        if item == b' ' {
            return &s[0..i];     // 找到空格，返回空格前的切片
        }
    }
    &s[..]   // 没找到空格，整个字符串就是一个单词
}

fn print_str(s: &str) {
    println!("print_str: {s}");
}
