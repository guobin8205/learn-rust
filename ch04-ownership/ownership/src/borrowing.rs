// ===== 4.2 引用与借用 (References & Borrowing) =====
// 用 cargo run --bin borrowing 运行

fn main() {
    // ========================================================
    // 问题：4.1 中每次用 String 都要移进移出函数，太麻烦
    // 解决：用「引用」让函数「借用」数据，不拿走所有权
    // ========================================================

    let s1 = String::from("hello");

    // ---------- ① 不可变引用 &T ----------
    let len = calculate_length(&s1);   // 传 &s1（s1 的引用），不移动所有权
    println!("'{}' 的长度是 {}", s1, len);  // ✅ s1 仍然能用！

    // 引用在内存中的样子：
    //   栈：s1 → [ptr,len,cap] → 堆:[hello]
    //           ↑
    //        &s1（指针的指针，指向 s1）
    //   函数拿到的是 &s1，能读数据，但不拥有它

    // ---------- ② 可变引用 &mut ----------
    let mut s2 = String::from("hello");
    change(&mut s2);          // 传可变引用，函数能修改 s2
    println!("修改后 s2 = {s2}");   // hello, world

    // ⚠️ 用可变引用的前提：变量本身要是 mut
    // let s3 = String::from("...");  // 没有 mut
    // change(&mut s3);  // ❌ 编译错误

    // ========================================================
    // ⭐ 可变引用的两大限制规则（极易踩坑！）
    // ========================================================

    // ---------- ③ 规则一：同一时刻只能有一个可变引用 ----------
    let mut s3 = String::from("hello");
    let r1 = &mut s3;
    // let r2 = &mut s3;  // ❌ 编译错误！s3 同时有两个可变引用
    // 原因：防止数据竞争（data race）。如果两个引用同时改同一份数据就乱了
    println!("{r1}");

    // ---------- ④ 规则二：可变引用和不可变引用不能共存 ----------
    let mut s4 = String::from("hello");
    let r1 = &s4;       // 不可变引用
    let r2 = &s4;       // 不可变引用（多个不可变引用是 OK 的）
    // let r3 = &mut s4; // ❌ 编译错误！已经有不可变引用，不能再有可变引用
    println!("{r1}, {r2}");
    // ↑ r1、r2 在这之后不再使用（NLL：非词法生命周期，编译器知道它们失效了）

    let r3 = &mut s4;   // ✅ 现在可以用可变引用了（r1、r2 已经不再使用）
    println!("{r3}");

    // ---------- ⑤ 引用的作用域 ----------
    // 引用的作用域 = 从「创建」到「最后一次使用」之间（NLL 非词法生命周期）
    // 而不是到 {} 结束。这意味着引用"提前失效"，不会挡住后续的借用
    let mut s5 = String::from("hello");
    let r1 = &s5;       // 不可变引用
    let r2 = &s5;       // 不可变引用
    println!("{r1} {r2}");  // r1 r2 最后一次使用
    // ↑ 此后 r1 r2 失效（NLL），下面可以借可变引用了
    let r3 = &mut s5;   // ✅
    println!("{r3}");

    // ---------- ⑥ 悬垂引用 (Dangling Reference) ----------
    // Rust 不允许出现悬垂引用（指向已释放内存的指针）
    // fn dangle() -> &String {            // ❌ 编译错误
    //     let s = String::from("hi");
    //     &s   // s 在函数结束时被 drop，但返回了指向它的引用 → 悬垂！
    // }
    // 编译器会在编译期就阻止这种情况

    // ========================================================
    // ⭐ 借用的三大规则（必须记住！）
    // ========================================================
    // 1. 任意时刻，要么有「一个可变引用」，要么有「任意多个不可变引用」
    // 2. 引用必须始终有效（不能悬垂）
    // 3. (隐含) 引用比所有者活得更短
}

fn calculate_length(s: &String) -> usize {
    s.len()
} // ← s 离开作用域，但因为它不拥有所有权，什么也不会发生

fn change(some_string: &mut String) {
    some_string.push_str(", world");
}
