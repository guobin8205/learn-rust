// ===== 4.1 所有权规则与移动 (Ownership & Move) =====
// 用 cargo run --bin ownership_rules 运行

fn main() {
    // ========================================================
    // 🔑 所有权三大规则（必须背下来！）
    // ========================================================
    // 1. 每个值都有一个「所有者」(owner) 变量
    // 2. 同一时刻，值只能有「一个」所有者
    // 3. 当所有者离开作用域，值被自动 drop（释放）

    // ---------- 栈 vs 堆（理解所有权的前提）----------
    // 栈 Stack：后进先出，存「编译期已知大小」的数据，速度快
    //   - 整数、浮点、布尔、char、(全栈元素的)元组 → 直接拷贝
    // 堆 Heap：存「运行时才知道大小」的数据，访问慢
    //   - String、Vec、Box 等 → 涉及所有权转移

    // ========================================================
    // 一、字符串字面量 vs String（理解堆数据）
    // ========================================================

    let _s1 = "hello";              // 字面量 &str，编译时写死在二进制里，不可变
    let _s2 = String::from("hello"); // String，在堆上分配，可变、可增长

    // String 在内存中的样子：
    //   栈上（3 个字段）：            堆上：
    //   ┌──────────────┐            ┌───┬───┬───┬───┬───┐
    //   │ ptr ───────────────→      │ h │ e │ l │ l │ o │
    //   │ len = 5      │            └───┴───┴───┴───┴───┘
    //   │ capacity = 5 │
    //   └──────────────┘
    //   栈上存指针 ptr、长度 len、容量 capacity
    //   ptr 指向堆上实际存 "hello" 的内存

    // ========================================================
    // 二、变量赋值：拷贝 vs 移动（核心！）
    // ========================================================

    // ---------- ① 栈数据：Copy（拷贝）----------
    let x = 5;
    let y = x;     // x 的值 5 被拷贝给 y，x 和 y 各自独立持有 5
    println!("栈拷贝: x={x}, y={y}");   // 两个都能用

    // 为什么能拷贝？因为整数大小固定、存在栈上，拷贝代价很低
    // 实现了 Copy trait 的类型：整数、浮点、布尔、char、&引用、(全 Copy 元素的)元组

    // ---------- ② 堆数据：Move（移动）⭐ 核心 ----------
    let s1 = String::from("hello");
    let s2 = s1;   // ⚠️ 不是拷贝！s1 的所有权「移动」给了 s2

    // 移动后发生了什么？
    //   移动前：                          移动后：
    //   栈：s1 → [ptr,len,cap]            栈：s1 → [已失效，不能再使用]
    //            ↓                              s2 → [ptr,len,cap]（接管了堆数据）
    //   堆：    [hello]                     堆：    [hello]（同一块，现在归 s2 所有）
    //
    // ⚠️ 关键：移动后 s1 被标记为「无效」，不能再使用！
    // println!("{s1}");  // ❌ 编译错误：borrow of moved value: `s1`

    println!("移动后 s2 = {s2}");  // ✅ 只有 s2 能用

    // ---------- ③ 为什么 String 移动而不是拷贝？----------
    // 如果是拷贝：需要把堆上的 "hello" 也复制一份（昂贵！）
    //   并且会有两个指针指向同一块堆内存 → s1、s2 离开作用域都会 drop → double free（双重释放）！
    // 移动的意义：保证「同一时刻只有一个所有者」，避免 double free

    // ========================================================
    // 三、函数调用也会发生移动（容易踩坑！）
    // ========================================================

    let s = String::from("hello");
    takes_ownership(s);   // ⚠️ s 的值移动进了函数
    // println!("{s}");   // ❌ 编译错误！s 已经移动了，不能再用

    let num = 5;
    makes_copy(num);      // num 是 Copy，拷贝一份进去
    println!("函数后 num 还能用: {num}");   // ✅ num 仍可用

    // ---------- 函数返回值也会转移所有权 ----------
    let s3 = gives_ownership();      // 函数返回的 String 所有权移动给 s3
    println!("s3 = {s3}");

    let s4 = String::from("world");
    let s5 = takes_and_gives_back(s4);  // s4 移进去，又被返回移出来给 s5
    // println!("{s4}");  // ❌ s4 已经移动进函数了
    println!("s5 = {s5}");

    // ========================================================
    // 四、克隆 Clone（真的需要深拷贝时用）
    // ========================================================
    let s6 = String::from("hello");
    let s7 = s6.clone();   // 显式深拷贝堆数据，s6 仍然有效
    println!("克隆: s6={s6}, s7={s7}");   // 两个都能用

    // 💡 clone 有运行时代价（要复制堆数据），所以 Rust 让你显式写出来
    //    看到代码里有 .clone() 就知道「这里有深拷贝开销」

    // ========================================================
    // 五、Copy 与 Move 的判定：看是否实现了 Copy trait
    // ========================================================
    // | 类型                  | 行为   | 原因                       |
    // |----------------------|--------|---------------------------|
    // | 整数/浮点/布尔/char    | Copy   | 栈上，大小固定              |
    // | &T 不可变引用          | Copy   | 只是借用，不拥有数据         |
    // | (Copy, Copy) 元组     | Copy   | 所有元素都 Copy            |
    // | String               | Move   | 有堆数据，不能简单拷贝       |
    // | Vec<T>               | Move   | 有堆数据                   |
    // | (String, i32) 元组    | Move   | 含有非 Copy 元素           |
}

fn takes_ownership(some_string: String) {
    println!("函数接管: {some_string}");
} // ← some_string 离开作用域，被 drop（堆内存释放）

fn makes_copy(some_integer: i32) {
    println!("函数拷贝: {some_integer}");
} // ← some_integer 离开作用域，没事发生（栈数据自动回收）

fn gives_ownership() -> String {
    String::from("来自函数")   // 所有权移出给调用者
}

fn takes_and_gives_back(a_string: String) -> String {
    a_string   // 进来的 String 又被返回，所有权移回给调用者
}
