// ===== 15.1 Box<T> 堆分配 =====
// 用 cargo run --bin box_t 运行

fn main() {
    println!("===== 1. Box 基础：把数据放到堆上 =====\n");

    // 普通变量 i32 在栈上
    let x = 5;
    println!("x 在栈上: {}", x);

    // Box 把数据放到堆上，栈上只存指针
    let b = Box::new(5);
    println!("b 是 Box 指向堆: {}", b);   // 自动解引用，用起来和普通变量一样

    // ⭐ Box 没有额外性能开销（除了堆分配本身）
    //    在很多场景下 Box 让你能做到「栈类型做不到的事」

    println!("\n===== 2. Box 的核心用途 =====\n");

    // ---------- 用途 1：存大小未知/递归类型（最重要）----------
    // 递归类型：类型包含自己 → 大小无限 → 必须用 Box 引入间接性
    let list = List::Cons(1, Box::new(List::Nil));
    println!("递归链表: {:?}", list);

    // 为什么必须用 Box？
    // 如果不用 Box：
    //   enum List { Cons(i32, List), Nil }
    //   编译器算大小：List = i32 + List = i32 + (i32 + List) = ... 无限大！
    //
    // 用 Box 后：
    //   enum List { Cons(i32, Box<List>), Nil }
    //   List = i32 + Box<List> = i32 + 指针（固定大小）✅

    println!("\n===== 3. Box 的其他用途 =====\n");

    // ---------- 用途 2：大数据放到堆上 ----------
    // 注意：Box::new 先在栈上构造再移到堆，所以不能太大
    // 真正大的数据用 vec!（直接在堆上构造）
    let big_data = vec![0u64; 100_000];  // 80 万个 u64，在堆上
    println!("大数据长度: {}", big_data.len());

    // ---------- 用途 3：转移数据所有权（不拷贝）----------
    fn process(data: Box<i32>) { println!("处理: {}", data); }
    let owned = Box::new(42);
    process(owned);   // Box 移动进函数，零拷贝
    // println!("{}", owned);  // ❌ 已被 move

    // ---------- 用途 4：trait 对象（第 17 章详讲）----------
    // 把不同类型统一成「实现了某 trait 的东西」
    let shapes: Vec<Box<dyn std::fmt::Debug>> = vec![
        Box::new(1),
        Box::new("hello"),
        Box::new(3.14),
    ];
    println!("不同类型放一起: {:?}", shapes);

    println!("\n===== 4. Box vs 普通引用 =====\n");

    let x = 5;
    let r = &x;            // 引用：不拥有数据，只在作用域内有效
    let b = Box::new(x);   // Box：拥有数据，自己 drop 时释放
    println!("引用 {} Box {}", r, b);

    // | 特性       | &T 引用       | Box<T>          |
    // |-----------|--------------|-----------------|
    // | 所有权     | 无            | 有               |
    // | 数据位置   | 引用别处      | 堆上             |
    // | 可变       | 取决于 &/&mut | 拥有，可修改     |
    // | 生命周期   | 借用规则      | 跟 Box 变量走    |
}

// ========================================================
// 递归类型：Cons List（经典例子）
// ========================================================
// 这是 Lisp 语言的链表结构，Rust 经典教学例子
#[derive(Debug)]
enum List {
    Cons(i32, Box<List>),   // 持有一个值 + 指向下一个的 Box
    Nil,                    // 空链表
}

// ========================================================
// ⭐ 智能指针概念预告
// ========================================================
// Box 是最简单的智能指针，还有：
//
// | 指针类型   | 所有权模型         | 用途                |
// |-----------|-------------------|--------------------|
// | Box<T>    | 单一所有者         | 堆分配、递归类型     |
// | Rc<T>     | 多个所有者（引用计数）| 共享只读数据        |
// | Arc<T>    | 原子引用计数       | 多线程共享          |
// | RefCell<T>| 运行时借用检查     | 内部可变性          |
//
// 它们都「像指针」但拥有额外能力（自动释放、引用计数等）
