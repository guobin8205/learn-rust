// ===== 9.1 panic! 不可恢复错误 =====
// 用 cargo run --bin panic_t 运行

fn main() {
    println!("程序开始...");

    // ========================================================
    // 一、什么是 panic？
    // ========================================================
    // panic 是「不可恢复」的错误——程序直接崩溃退出
    // 适用场景：
    //   - 代码出错但不知道怎么处理（比如数组越界）
    //   - 不应该发生的情况（违反了不变式/约定）
    //   - 原型/演示代码快速验证

    // ========================================================
    // 二、两种触发 panic 的方式
    // ========================================================

    // ---------- 方式 1：代码行为触发（如越界）----------
    // let v = vec![1, 2, 3];
    // let crash = v[99];     // 💥 panic: index out of bounds
    // 这不是我们手动调 panic!，而是标准库检测到错误后 panic

    // ---------- 方式 2：手动调用 panic! 宏 ----------
    // panic!("出错了！");     // 💥 直接 panic，打印这条消息

    // ========================================================
    // 三、实际场景：用 panic 处理「不该发生」的情况
    // ========================================================

    // 例子 1：分支不应该走到（取消注释会 panic）
    let color = "red";     // 改成已知的颜色，演示正常流程
    match color {
        "red" => println!("红色"),
        "green" => println!("绿色"),
        "blue" => println!("蓝色"),
        _ => panic!("未知颜色: {color}"),   // 如果 color 是其他值会 panic
    }
    // 试一试：把 color 改成 "purple"，运行会看到 panic 的真实效果

    // 例子 2：unwrap 遇到 None 时 panic（第 6 章学过）
    let x: Option<i32> = None;
    // x.unwrap();    // 💥 panic: called Option::unwrap() on a None value

    // 例子 3：用 unwrap_or 避免 panic
    let safe = x.unwrap_or(0);
    println!("安全的取值: {safe}");

    // ========================================================
    // 四、panic 的展开过程（unwinding）
    // ========================================================
    // panic 发生时，Rust 会：
    //   1. 打印错误信息和调用栈
    //   2. 逐层清理（unwinding）每个函数的栈
    //   3. 调用所有对象的 Drop（释放资源）
    //   4. 退出进程（退出码非 0）

    // 看一个 panic 的 backtrace：
    // 设置环境变量 RUST_BACKTRACE=1 可以看到详细调用栈
    // RUST_BACKTRACE=1 cargo run --bin panic_t

    // ========================================================
    // 五、什么时候该 panic，什么时候不该？
    // ========================================================
    // | 场景                        | 该 panic 吗？ | 理由                |
    // |----------------------------|--------------|--------------------|
    // | 数组越界                    | ✅（标准库会）| 程序逻辑错误         |
    // | 配置文件格式错误             | ⚠️ 看情况     | 启动时可 panic，运行时不应 |
    // | 用户输入错误                 | ❌           | 应该用 Result 返回   |
    // | 网络请求失败                 | ❌           | 应该用 Result 返回   |
    // | 文件不存在                   | ❌           | 应该用 Result 返回   |
    // | 代码进入不可能的分支          | ✅           | 程序逻辑错误         |
    // | 解析字符串失败                | ❌           | 应该用 Result 返回   |
    //
    // 💡 核心原则：
    //    「可以恢复的错误」用 Result（让调用者决定怎么办）
    //    「不该发生的情况」用 panic（程序已经处于错误状态，继续不安全）
}

// ========================================================
// 演示 panic 的调用栈（如果去掉注释运行会看到 backtrace）
// ========================================================
#[allow(dead_code)]
fn a() { b(); }
#[allow(dead_code)]
fn b() { c(); }
#[allow(dead_code)]
fn c() {
    panic!("崩溃在 c() 函数");
    // 运行时会显示：
    //   thread 'main' panicked at '崩溃在 c() 函数'
    //   stack backtrace:
    //      0: errors::c
    //      1: errors::b
    //      2: errors::a
    //      3: errors::main
}
